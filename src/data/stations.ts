export const formatCurrency = (amount: number) =>
  new Intl.NumberFormat('vi-VN', { style: 'currency', currency: 'VND', maximumFractionDigits: 0 }).format(amount);

export const formatPower = (station: ChargingStation) =>
  station.powerKw < 3 ? `${Math.round(station.powerKw * 1000)} W` : `${station.powerKw} kW`;

export const formatStationPrice = (station: ChargingStation) => {
  if (station.pricingMode === 'flat') return station.flatFee ? `${formatCurrency(station.flatFee)}/lần` : 'Miễn phí';
  return `${formatCurrency(station.pricePerKwh)}/kWh`;
};

export const getDirectionsUrl = (station: ChargingStation) =>
  `https://www.google.com/maps/dir/?api=1&destination=${station.latitude},${station.longitude}&travelmode=driving`;
